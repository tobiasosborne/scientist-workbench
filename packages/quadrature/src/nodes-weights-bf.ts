// =============================================================================
// nodes-weights-bf.ts — G7K15 nodes and weights at arbitrary precision
// =============================================================================
//
// Intent
// ------
// The arb-prec G7K15 driver (`gauss-kronrod-bf.ts`) needs the seven-point
// Gauss-Legendre + 15-point Kronrod nodes and weights as `BigFloat` values
// rounded to its working precision. This file is the single source of truth
// for those constants, and the only home in the package where 200-decimal-
// digit literals live.
//
// We *cannot* derive these from the float64 GSL constants in `gauss-kronrod.ts`
// — those carry only ~16 trustworthy digits, and naively converting via
// `fromFloat64` would re-introduce float64-precision rounding into a substrate
// we are deliberately keeping above it. The arb-prec values are stored as
// 200-dps decimal string literals and parsed lazily into the requested
// working precision via `fromString`.
//
// Generation oracle (the cited regeneration recipe — Law 1 & 2)
// -------------------------------------------------------------
// All constants below were generated by the script transcribed in this
// header comment. Rerunning the script at `mp.dps = 230` reproduces the
// values byte-for-byte (the 200-dps strings are the leading-200-digit
// truncation of mpmath's 230-dps output; the 30-digit safety margin is
// absorbed by mpmath's internal rounding). Saved as a comment, not a
// committed `.py` file, because the regeneration is rare and auditing
// the recipe in-place beats hunting for a sibling script.
//
// ```python
// from mpmath import mp, mpf, polyroots, lu_solve, matrix, quad
// mp.dps = 230
//
// # Gauss-Legendre 7-point nodes via P_7 root-finding (substitute u=x^2):
// u_roots = sorted(polyroots([mpf(429), mpf(-693), mpf(315), mpf(-35)]))
// gauss_pos_asc = [mp.sqrt(u) for u in u_roots]
//
// # Stieltjes polynomial E_8 via orthogonality to P_7(x) x^k for k=0..7
// # (k even → integrand odd → trivially zero; k odd → 4 non-trivial
// # equations for 4 even coefficients of E_8). Solve linear system.
// def P7(x): return (mpf(429)*x**7 - mpf(693)*x**5 + mpf(315)*x**3 - mpf(35)*x) / 16
// M = [[quad(lambda x, j=j, k=k: P7(x) * x**(2*j + 1 + 2*k), [-1, 1])
//       for k in range(5)] for j in range(4)]
// A = matrix([[M[j][k] for k in range(4)] for j in range(4)])
// b = matrix([-M[j][4] for j in range(4)])
// c0, c2, c4, c6 = lu_solve(A, b)
// u_kron = sorted(polyroots([mpf(1), c6, c4, c2, c0]))
// kron_pos = [mp.sqrt(u) for u in u_kron]
//
// # K15 abscissae sorted by descending |x| (GSL convention; centre last):
// xgk_by_index = sorted(gauss_pos_asc + kron_pos, reverse=True) + [mpf(0)]
//
// # K15 weights via Vandermonde-on-x^{2k} for k=0..7 (8 equations,
// # 8 unknowns: 7 paired weights + 1 centre weight):
// A_w = matrix(8, 8); b_w = matrix(8, 1)
// for k in range(8):
//     for i in range(7):
//         A_w[k, i] = 2 * xgk_by_index[i]**(2*k)
//     A_w[k, 7] = mpf(1) if k == 0 else mpf(0)
//     b_w[k, 0] = mpf(2) / mpf(2*k + 1)
// w_kron = lu_solve(A_w, b_w)
//
// # G7 weights at the Gauss-shared and centre positions:
// def dP7(x): return (mpf(7*429)*x**6 - mpf(5*693)*x**4 + mpf(3*315)*x**2 - mpf(35)) / 16
// wg_centre = mpf(2) / dP7(mpf(0))**2
// wg_desc = list(reversed([mpf(2) / ((1 - x**2) * dP7(x)**2) for x in gauss_pos_asc]))
//
// # Cancellation-stable difference weights (WGK[i] - WG_i) at Gauss positions:
// dwgk_gauss = [w_kron[1, 0] - wg_desc[0],   # XGK[1] is the largest Gauss node
//               w_kron[3, 0] - wg_desc[1],   # XGK[3] mid Gauss
//               w_kron[5, 0] - wg_desc[2]]   # XGK[5] smallest Gauss (positive)
// dwgk_centre = w_kron[7, 0] - wg_centre
// ```
//
// Cross-validation (Law 1)
// ------------------------
// 1. **Truncating to float64 reproduces GSL `qk15.c` byte-for-byte** at all
//    16 entries (XGK[0..7], WGK[0..7], WG[0..3]). Verified during the
//    initial generation: `|truncated_arbprec_value - GSL_float64_value|
//    = 0.0` at all positions. GSL's source comment states the constants
//    were "evaluated with 80 decimal digit arithmetic by L. W. Fullerton,
//    Bell Labs, Nov. 1981" — well above float64; our 200-dps regeneration
//    matches Fullerton's truncation exactly.
// 2. **Algebraic exactness on x^{2k}, k=0..11** (degrees 0..22; K15 is
//    exact through degree 23): the Vandermonde-residual under our
//    constants is at the mpmath-floor (~1e-231 at 230 dps) for every
//    such k, and a non-trivial 5.7e-9 at degree 24 (k=12), confirming
//    the 23-degree exactness boundary.
//
// Cap (Law 8 — honest scope)
// --------------------------
// Maximum supported decimal precision is `MAX_DECIMAL_PRECISION = 150`. The
// 200-dps storage gives a 50-dps safety margin; after `decimalToBinaryPrecision
// (150, safety=30)` the working precision is ~530 bits, comfortably below
// the table's ~665-bit storage. A user requesting `prec > 150` gets a
// loud `RangeError`. ADR-0021 records the rationale; if a workload demands
// it, extend the table (or compute via Golub-Welsch on the Jacobi matrix
// at runtime) — do not silently degrade.

import {
  type BigFloat,
  fromString,
  decimalToBinaryPrecision,
} from "@workbench/bigfloat";

