// -----------------------------------------------------------------------------
// Public API: cap and the lazily-cached BigFloat table
// -----------------------------------------------------------------------------

/**
 * Maximum decimal precision the arb-prec G7K15 driver supports. Beyond this,
 * the stored 200-dps constants no longer give the working precision enough
 * headroom — we refuse loudly rather than silently degrade.
 *
 * Senior-engineer rule (Law 8 — honest scope): a tool that produces a wrong-
 * shaped or wrong-valued answer past its declared scope is inadmissible, no
 * matter how cleverly it tries. The 150-dps cap is the line.
 */
export const MAX_DECIMAL_PRECISION = 150;

/**
 * The G7K15 nodes and weights, parsed at a specific working bit-precision.
 *
 * The driver requests this at its working precision (typically `prec * 3.32
 * + 30` bits for a `prec`-decimal-digit user request); the parsed table is
 * cached so successive bisections share one table.
 */
export interface G7K15Table {
  /** Bit precision the table is parsed at. */
  readonly workingBits: number;
  /** Positive Kronrod abscissae, descending magnitude; index 7 is the centre (0). */
  readonly xgk: readonly BigFloat[];
  /** Kronrod weights at `±xgk[i]` (and centre at index 7). */
  readonly wgk: readonly BigFloat[];
  /** Gauss weights: indices 0..2 at `±xgk[1]`, `±xgk[3]`, `±xgk[5]`; index 3 is centre. */
  readonly wg: readonly BigFloat[];
  /**
   * Precomputed `WGK[2k+1] − WG[k]` differences for k=0..2 — used by the
   * cancellation-stable error estimator. Negative-valued.
   */
  readonly wgkMinusWg: readonly BigFloat[];
  /** `WGK[7] − WG[3]` — centre's cancellation-stable difference. */
  readonly wgkMinusWgCentre: BigFloat;
}

const tableCache = new Map<number, G7K15Table>();

/**
 * Get the G7K15 nodes/weights table at the given working bit precision.
 *
 * First call at a given `workingBits` parses the 200-dps strings into
 * BigFloat values and caches the table; subsequent calls at the same
 * precision return the cached table directly. Cache is unbounded (one
 * entry per distinct working precision); the typical adaptive driver
 * uses one precision throughout a run, so the cache never grows past
 * a small handful of entries even across many `gaussKronrodAdaptiveBF`
 * invocations.
 *
 * Throws `RangeError` if `workingBits < 1` or if the requested precision
 * would correspond to more than `MAX_DECIMAL_PRECISION` decimal digits
 * (with the standard 30-bit safety margin removed, i.e. the user-facing
 * limit; the bit-precision boundary is a conservative restatement of
 * the decimal cap).
 */
export function getG7K15Table(workingBits: number): G7K15Table {
  if (!Number.isInteger(workingBits) || workingBits < 1) {
    throw new RangeError(
      `getG7K15Table: workingBits must be a positive integer; got ${workingBits}`,
    );
  }
  // Defensive cap: convert MAX_DECIMAL_PRECISION to bits and refuse anything
  // beyond. The driver's `prec ≤ MAX_DECIMAL_PRECISION` check happens at
  // the user surface; this is a belt-and-braces internal guard against a
  // caller routing an unexpected working precision through.
  const maxBits = decimalToBinaryPrecision(MAX_DECIMAL_PRECISION, 30);
  if (workingBits > maxBits) {
    throw new RangeError(
      `getG7K15Table: workingBits=${workingBits} exceeds the table's safe ` +
        `precision ceiling (${maxBits} bits ≈ ${MAX_DECIMAL_PRECISION} decimal digits ` +
        `with 30-bit safety). Extend the 200-dps tables in nodes-weights-bf.ts ` +
        `or compute weights at runtime via Golub-Welsch on the Jacobi matrix.`,
    );
  }

  const cached = tableCache.get(workingBits);
  if (cached !== undefined) return cached;

  const table: G7K15Table = {
    workingBits,
    xgk: XGK_DPS200.map((s) => fromString(s, workingBits)),
    wgk: WGK_DPS200.map((s) => fromString(s, workingBits)),
    wg: WG_DPS200.map((s) => fromString(s, workingBits)),
    wgkMinusWg: WGK_MINUS_WG_DPS200.map((s) => fromString(s, workingBits)),
    wgkMinusWgCentre: fromString(WGK_MINUS_WG_CENTRE_DPS200, workingBits),
  };
  tableCache.set(workingBits, table);
  return table;
}

/**
 * Clear the parsed-table cache. Test-only escape hatch; production code
 * never needs this. Exposed so a long-running orchestrator that processes
 * many distinct precisions in sequence can reclaim memory if it really
 * wants to (in practice the cache stays tiny).
 */
export function _clearG7K15TableCacheForTesting(): void {
  tableCache.clear();
}
