// =============================================================================
// gen-catalog — regenerate the generated tool catalog from the registry
// =============================================================================
//
// Substrate: ADR-0043 (the tool registry is the single source of truth for
// tool-facing docs), issues scientist-workbench-ixnv.2 (the catalog
// generator) and scientist-workbench-ixnv.4 (the tiered progressive-
// discovery model — which is why the catalog now lives in its own file).
//
// What this script does
// ---------------------
// It walks `tools/`, imports each tool's `def` (ADR-0010 guarantees that
// importing a tool module is side-effect-free — the `runTool` call is gated
// on `import.meta.main`), and emits a Markdown table of every tool's name
// and one-line `summary`. The table is written to `docs/CATALOG.md` as a
// fully generated file carrying the `AUTOGENERATED` banner.
//
// Why `docs/CATALOG.md` and not `README.md` (the ixnv.4 relocation)
// -----------------------------------------------------------------
// The keystone child `ixnv.2` originally wrote the catalog into a marked
// region inside `README.md`. Child `ixnv.4` collapses `README.md` into a
// ~35-line Tier-0 bootstrap under the progressive-discovery model: the
// README no longer carries a 55-row table. The catalog therefore moves to
// its own generated file, `docs/CATALOG.md` — reachable from the Tier-0
// README by a link, and a sibling of the live-registry listing the `wb`
// discovery CLI prints (`bun wb.ts` with no args). The whole file is
// generated (banner at the top), not a region inside a hand-written file,
// so there is no marker-pair bookkeeping: regeneration overwrites the file
// wholesale.
//
// Why this exists at all
// ----------------------
// Before ADR-0043 the catalog was ~55 hand-copied rows, each one a Law-2
// lockstep liability: when a tool's identity changed, a human had to
// remember to re-edit the row, and nothing failed the build when they
// forgot. The catalog already drifted. This generator makes the registry —
// the validated, machine-readable record of tool identity — the single
// source of truth, exactly as `scripts/gen-workbench-barrel.ts` already
// does for the typed-barrel code. The catalog is a derived artefact;
// `scripts/check.ts` regenerates it and byte-compares against the committed
// file, so a stale catalog cannot be committed without `bun run check`
// going red.
//
// The table shape — terse `tool | summary`, ADR-0043 Decision 3
// -------------------------------------------------------------
// ADR-0043 Decision 3 specifies a row of `name | input | output | summary`.
// In practice the rich per-tool input/output schema rendering belongs in
// the per-tool `tools/<name>/README.md` (and in `bun wb.ts <tool>`) under
// the progressive-discovery model the epic establishes: the catalog is an
// *index*, scanned by name, and a reader who wants the schema follows the
// link or asks `wb`. A `tool | summary` table — with a link out to the
// per-tool README — keeps each row to one scannable line and avoids
// duplicating the schema rendering that `--schema` and the per-tool README
// already own. The `summary` itself, per Decision 2, is dense enough to
// carry the algorithm, the determinism tier, and the scope boundary in one
// declarative sentence, which is the information a planner scanning the
// index actually needs.
//
// Byte-stability
// --------------
// The walk is sorted by directory name (the same discipline
// `gen-workbench-barrel.ts` follows), so regenerating against an unchanged
// tool set is a byte-stable no-op. A generator that was not byte-stable
// would turn every `check` run red — the drift check is an exact compare.
//
// A tool that has not yet been back-filled with a `summary` (ADR-0043
// leaves the field optional precisely so back-fill is incremental) renders
// with an explicit `_(no summary — add a \`summary\` field to tool.ts)_`
// placeholder rather than an empty cell, so the gap is visible in the
// rendered catalog and an agent is nudged to fill it.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { findToolsRoot, importToolDef, listToolEntries } from "@workbench/contract";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = dirname(HERE);
const CATALOG_PATH = join(ROOT, "docs", "CATALOG.md");

// The generated-file banner. `docs/CATALOG.md` is a fully generated file —
// not a region inside a hand-written file — so the banner is the whole
// file's header rather than a marker pair. It mirrors the banner
// `gen-workbench-barrel.ts` emits at `wb.ts:120-122`: an `AUTOGENERATED`
// line plus the exact regeneration command, so a human (or agent) who opens
// the file knows immediately that hand-edits will be clobbered and which
// command owns it.
const BANNER =
  "<!-- AUTOGENERATED:catalog — do not edit by hand. " +
  "Regenerate with `bun scripts/gen-catalog.ts`. -->";

/**
 * Render the catalog table body — one row per tool, sorted by name. The
 * pipe characters in a `summary` are escaped so a stray `|` in a blurb
 * cannot break the Markdown table.
 */
function renderTable(rows: { name: string; summary: string | undefined }[]): string {
  const lines: string[] = [];
  lines.push("| tool | summary |");
  lines.push("|---|---|");
  for (const r of rows) {
    const blurb =
      r.summary === undefined
        ? "_(no summary — add a `summary` field to tool.ts)_"
        : r.summary.replace(/\|/g, "\\|");
    // Each row renders the tool name as a link to its per-tool README
    // (the progressive-discovery path of ADR-0043 — schema detail lives
    // there, not in this index), then the one-line summary. The link is
    // relative to `docs/CATALOG.md`, so it climbs one level to `tools/`.
    lines.push(`| [\`${r.name}\`](../tools/${r.name}/README.md) | ${blurb} |`);
  }
  return lines.join("\n");
}

/**
 * Assemble the whole `docs/CATALOG.md` file: the banner, a short prose
 * preamble explaining the file is generated and pointing at the `wb`
 * discovery CLI, and the table.
 */
function renderCatalog(rows: { name: string; summary: string | undefined }[]): string {
  const parts: string[] = [];
  parts.push(BANNER);
  parts.push("");
  parts.push("# Tool catalog");
  parts.push("");
  parts.push(
    "This file is **generated from the tool registry** (ADR-0043): every " +
      "row is derived from the corresponding `tool.ts`'s `def.name` and " +
      "`def.summary`. Do not hand-edit it — run `bun scripts/gen-catalog.ts`, " +
      "and `bun run check` enforces that it stays current.",
  );
  parts.push("");
  parts.push(
    "The same list is available live from the discovery CLI: `bun wb.ts` " +
      "lists every tool from the live registry, `bun wb.ts <tool>` shows one " +
      "tool's schema / examples / invariants, and `bun wb.ts search` filters " +
      "by type. Per-tool detail (input/output schemas, algorithm, refusal " +
      "envelope) lives in `tools/<name>/README.md` — each row links out.",
  );
  parts.push("");
  parts.push(`${rows.length} tools.`);
  parts.push("");
  parts.push(renderTable(rows));
  parts.push("");
  return parts.join("\n");
}

async function main(): Promise<void> {
  const toolsRoot = await findToolsRoot(ROOT);
  if (toolsRoot === null) {
    throw new Error(
      "gen-catalog: findToolsRoot returned null; run from inside the workbench checkout",
    );
  }

  // `listToolEntries` already returns the tools sorted by directory name,
  // which is what makes the generated table byte-stable.
  const entries = await listToolEntries(toolsRoot);
  const rows: { name: string; summary: string | undefined }[] = [];
  for (const e of entries) {
    let def;
    try {
      def = await importToolDef(e.path);
    } catch (err) {
      // A tool whose module fails to import cannot be catalogued. The
      // error is loud and names the file — the developer fixes the tool
      // and reruns, exactly as `gen-workbench-barrel.ts` does.
      throw new Error(
        `gen-catalog: failed to import ${e.path}: ${(err as Error).message}`,
      );
    }
    rows.push({ name: def.name, summary: def.summary });
  }

  const next = renderCatalog(rows);

  // Read the existing file (if any) so a no-op regeneration is reported as
  // such rather than rewriting identical bytes — keeps `git status` quiet
  // and makes the byte-stability guarantee observable.
  let before: string | null = null;
  try {
    before = await readFile(CATALOG_PATH, "utf8");
  } catch {
    // File does not exist yet — first generation. `next` is written below.
  }

  if (before === next) {
    process.stdout.write(
      `gen-catalog: ${relative(ROOT, CATALOG_PATH)} already current (${rows.length} tools)\n`,
    );
    return;
  }
  await writeFile(CATALOG_PATH, next);
  process.stdout.write(
    `gen-catalog: wrote ${relative(ROOT, CATALOG_PATH)} (${rows.length} tools)\n`,
  );
}

await main();
