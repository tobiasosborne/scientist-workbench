// =============================================================================
// gen-tool-readme — regenerate every `tools/<name>/README.md` from the registry
// =============================================================================
//
// Substrate: ADR-0043 (the tool registry is the single source of truth for
// tool-facing docs), issue `scientist-workbench-ixnv.5` — the per-tool
// README generator, the final child of the `ixnv` epic. Sibling of
// `scripts/gen-catalog.ts` and `scripts/gen-workbench-barrel.ts`: the same
// walk-`tools/`, import-each-`def`, emit, byte-compare-in-`check.ts`
// pattern, applied here to the per-tool README.
//
// What this script does
// ---------------------
// It walks `tools/`, imports each tool's `def` (ADR-0010 guarantees the
// import is side-effect-free — the `runTool` call is gated on
// `import.meta.main`), reads the tool's `tool.ts` literate header, and
// writes a fully generated `tools/<name>/README.md` carrying the
// `AUTOGENERATED` banner. Hand-edits to a generated README are a
// `check.ts` drift-phase failure.
//
// The header → README extraction contract (ADR-0043 Decision 5)
// -------------------------------------------------------------
// ADR-0043 Decision 5 is binding and decides the whole approach: the
// `tool.ts` literate header is **canonical** prose; the per-tool README is
// **generated** — its mechanical sections from `def`, its prose ("How it
// works") *extracted from the canonical header*. Decision 5 leaves the
// exact marker grammar to this child; the grammar this generator fixes is:
//
//   1. The literate header is the contiguous run of `//`-prefixed lines at
//      the very top of `tool.ts` (from line 1 to the first non-`//`,
//      non-blank line — typically the first `import`).
//
//   2. Inside that block, a *section* is a `Name` line immediately
//      followed by an underline of `-` characters (`Intent` / `------`).
//      This is the lightweight section convention `scripts/new-tool.ts`
//      already scaffolds and `tools/mod-pow/tool.ts` already uses. Banner
//      rules (`// ====…`) and the title line (`// <name> — …`) are
//      stripped; text before the first section is the header *lead*.
//
//   3. The generator recognises exactly ONE required section name:
//      `Intent`. Every header MUST carry an `Intent` section — it is the
//      anchor that proves the header was written as deliberate exposition
//      (Rule 10) rather than left as a thin stub. A header with no
//      `Intent` section is a FAIL-LOUD error (Rule 1): the generator
//      throws, naming the offending tool and the missing section, rather
//      than emitting a silently thin README.
//
//   4. The README's "How it works" prose is the header *lead* plus the
//      `Intent` section plus EVERY section after it, with the underlined
//      section headers demoted to Markdown `###` sub-headings. Nothing in
//      the header is dropped — the header is canonical, so the whole of it
//      is reader-facing prose. The `Input` / `Output` / `Run` /
//      `Invariants` / `Standard flags` blocks are regenerated from `def`
//      and rendered separately; a header section that happens to restate
//      input/output shape is harmless (it is the canonical exposition of
//      *why* that shape was chosen — Decision 4's bright line).
//
// Why "require `Intent`, render everything after it" rather than a fixed
// set of pulled section names: the 55 headers are genuinely heterogeneous
// (some carry `Algorithm`, `References`, `Boundary categories`,
// `I/O contract`; some are freeform). A fixed pull-list would silently
// drop the sections it did not know about — exactly the "silently thin
// README" failure mode the task forbids. Requiring the one anchor section
// and rendering the rest verbatim is robust: a new header section a future
// author invents flows into the README automatically, and a header that
// was never written as exposition fails loud.
//
// Byte-stability
// --------------
// `listToolEntries` returns the tools sorted by directory name (the same
// discipline `gen-workbench-barrel.ts` and `gen-catalog.ts` follow), and
// the per-README rendering is a pure function of `def` + the header text,
// so regenerating against an unchanged tool set is a byte-stable no-op. A
// generator that was not byte-stable would turn every `check` run red —
// the drift check is an exact compare.

import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { canonicalize, type Schema, type SchemaNode, type Value } from "@workbench/protocol";
import {
  findToolsRoot,
  importToolDef,
  listToolEntries,
  type ExampleEntry,
  type ToolDefinition,
} from "@workbench/contract";

const HERE = dirname(fileURLToPath(import.meta.url));
const ROOT = dirname(HERE);
const CHECK = process.argv.includes("--check");

// The generated-file banner. Each `tools/<name>/README.md` is a fully
// generated file — not a region inside a hand-written file — so the
// banner is the whole file's header. It mirrors the banner
// `gen-catalog.ts` emits: an `AUTOGENERATED` line plus the exact
// regeneration command, so a human (or agent) who opens the file knows
// immediately that hand-edits will be clobbered and which command owns it.
const BANNER =
  "<!-- AUTOGENERATED:tool-readme — do not edit by hand. " +
  "Regenerate with `bun scripts/gen-tool-readme.ts`. " +
  "Prose comes from the tool.ts literate header (ADR-0043 Decision 5); " +
  "edit the header, not this file. -->";

// -----------------------------------------------------------------------------
// Header parsing — the extraction contract above, made concrete.
// -----------------------------------------------------------------------------

interface HeaderSection {
  /** The section name, e.g. `Intent`, `Algorithm`. */
  name: string;
  /** The section body, comment-prefix-stripped, trailing blanks trimmed. */
  body: string;
}

interface ParsedHeader {
  /** Prose before the first underlined section (after title + banners). */
  lead: string;
  /** The underlined sections, in document order. */
  sections: HeaderSection[];
}

/**
 * Extract the contiguous `//`-prefixed comment block at the top of a
 * `tool.ts` source string, with the `// ` prefix stripped from each line.
 * The block ends at the first line that is neither a `//` comment nor
 * blank — in every tool that is the first `import`.
 */
function extractHeaderBlock(source: string): string[] {
  const lines = source.split("\n");
  const out: string[] = [];
  for (const raw of lines) {
    const line = raw.replace(/\r$/, "");
    if (line.trim() === "") {
      // A blank line inside the leading comment block is kept (headers
      // use blank lines to separate paragraphs); a blank line *before*
      // any comment is skipped. We only reach here while still inside
      // the block, so keep it.
      out.push("");
      continue;
    }
    if (line.startsWith("//")) {
      // Strip `//` and a single following space if present.
      out.push(line.startsWith("// ") ? line.slice(3) : line.slice(2));
      continue;
    }
    // First non-comment, non-blank line — the header block is over.
    break;
  }
  // Drop trailing blank lines accumulated past the real prose.
  while (out.length > 0 && out[out.length - 1]!.trim() === "") out.pop();
  return out;
}

/**
 * Parse a comment-stripped header block into a lead + underlined
 * sections. `=====` banner rules and the `<name> — …` title line are
 * dropped; everything else is prose.
 */
function parseHeader(headerLines: string[]): ParsedHeader {
  // Drop banner rules (`====…`). The title is the first non-banner,
  // non-blank line; we drop exactly that one line.
  const noBanners = headerLines.filter((l) => !/^=+$/.test(l.trim()));
  let titleDropped = false;
  const body: string[] = [];
  for (const l of noBanners) {
    if (!titleDropped && l.trim() !== "") {
      titleDropped = true; // this is the `<name> — …` title; drop it
      continue;
    }
    body.push(l);
  }

  const lead: string[] = [];
  const sections: HeaderSection[] = [];
  let current: HeaderSection | null = null;
  for (let i = 0; i < body.length; i++) {
    const line = body[i]!;
    const next = body[i + 1];
    // An underlined-section header: a non-blank line followed by a line
    // that is all `-` characters (length ≥ 3).
    if (
      line.trim() !== "" &&
      next !== undefined &&
      /^-{3,}$/.test(next.trim()) &&
      // The header name itself is short — guards against a stray prose
      // line that happens to precede a `---` em-dash run.
      line.trim().length <= 60
    ) {
      current = { name: line.trim(), body: "" };
      sections.push(current);
      i++; // skip the underline
      continue;
    }
    if (current === null) {
      lead.push(line);
    } else {
      current.body += (current.body === "" ? "" : "\n") + line;
    }
  }
  return {
    lead: trimBlankEdges(lead.join("\n")),
    sections: sections.map((s) => ({ name: s.name, body: trimBlankEdges(s.body) })),
  };
}

/** Trim leading and trailing blank lines from a multi-line string. */
function trimBlankEdges(s: string): string {
  const lines = s.split("\n");
  while (lines.length > 0 && lines[0]!.trim() === "") lines.shift();
  while (lines.length > 0 && lines[lines.length - 1]!.trim() === "") lines.pop();
  return lines.join("\n");
}

// -----------------------------------------------------------------------------
// Schema rendering — a deterministic, compact, human-readable form.
// -----------------------------------------------------------------------------
//
// `def.schema.input` / `def.schema.output` are real `Schema` objects
// (ADR-0004). The README's `Input` / `Output` sections render them to a
// compact type expression — `record { base: integer, exponent: integer }`,
// `list<integer>`, `integer`. The rendering is deterministic (a pure
// function of the `SchemaNode` tree) so the generated README is
// byte-stable for an unchanged schema.

function renderSchema(s: Schema): string {
  return renderNode(s.node);
}

function renderNode(n: SchemaNode): string {
  switch (n.tag) {
    case "any":
      return "any";
    case "kind":
      return n.kind;
    case "literal":
      return literalToString(n.value);
    case "list":
      return `list<${renderNode(n.element.node)}>`;
    case "tuple":
      return `tuple[${n.items.map((it) => renderNode(it.node)).join(", ")}]`;
    case "record": {
      const parts: string[] = [];
      // Object key order is insertion order — deterministic for a
      // statically-declared `S.record({...})`.
      for (const [k, v] of Object.entries(n.fields)) {
        const opt = n.optional.has(k) ? "?" : "";
        parts.push(`${k}${opt}: ${renderNode(v.node)}`);
      }
      return `record { ${parts.join(", ")} }`;
    }
    case "expression": {
      if (n.head === null) return "expression";
      const args = n.args === null ? "…" : n.args.map((a) => renderNode(a.node)).join(", ");
      return `expression "${n.head}"(${args})`;
    }
    case "tagged": {
      const tag = n.tagName === null ? "…" : `"${n.tagName}"`;
      return `tagged ${tag} ${renderNode(n.payload.node)}`;
    }
    case "union":
      return n.alts.map((a) => renderNode(a.node)).join(" | ");
  }
}

/** Render a literal Value to a short string for a schema type expression. */
function literalToString(v: Value): string {
  switch (v.kind) {
    case "string":
      return `"${v.value}"`;
    case "symbol":
      return v.name;
    case "integer":
    case "rational":
    case "float64":
      return "value" in v ? String((v as { value: unknown }).value) : v.kind;
    case "boolean":
      return String(v.value);
    default:
      return v.kind;
  }
}

// -----------------------------------------------------------------------------
// Run-example rendering.
// -----------------------------------------------------------------------------
//
// The `Run` section is a templated `echo … | bun tools/<name>/tool.ts`
// line built from the tool's first example. Examples without a worked
// `output` (error-only examples) are skipped when picking the
// representative example; if no example carries an `output` the first
// example is used regardless.

function pickRunExample(def: ToolDefinition): ExampleEntry | undefined {
  const withOutput = def.examples.find((e) => e.output !== undefined);
  return withOutput ?? def.examples[0];
}

// -----------------------------------------------------------------------------
// README assembly.
// -----------------------------------------------------------------------------

function renderHowItWorks(parsed: ParsedHeader): string {
  const parts: string[] = [];
  if (parsed.lead.trim() !== "") parts.push(parsed.lead);
  for (const sec of parsed.sections) {
    // The `Intent` section's name is rendered as a sub-heading like any
    // other — the README reads as `## How it works` → `### Intent` →
    // `### Algorithm` …, mirroring the header's own structure.
    parts.push(`### ${sec.name}\n\n${sec.body}`);
  }
  return parts.join("\n\n");
}

function renderReadme(def: ToolDefinition, parsed: ParsedHeader): string {
  const out: string[] = [];
  out.push(BANNER);
  out.push("");
  out.push(`# ${def.name}`);
  out.push("");

  // Opening paragraph: the `summary` (ADR-0043 Decision 2 — the canonical
  // one-line blurb). A tool not yet back-filled renders an explicit
  // placeholder, mirroring `gen-catalog.ts`.
  if (def.summary !== undefined) {
    out.push(def.summary);
  } else {
    out.push("_(no summary — add a `summary` field to tool.ts)_");
  }
  out.push("");

  // Determinism tier — a one-line annotation derived from the manifest
  // flags (ADR-0005 / 0015 / 0020). Symbolic (the default) is stated
  // explicitly so the absence of an annotation is never ambiguous.
  out.push(`**Determinism:** ${determinismLine(def)}`);
  out.push(`**Version:** \`${def.version}\``);
  out.push("");

  // --- Input / Output (mechanical, from def.schema) ---
  out.push("## Input");
  out.push("");
  out.push("```");
  out.push(renderSchema(def.schema.input));
  out.push("```");
  out.push("");
  out.push("## Output");
  out.push("");
  out.push("```");
  out.push(renderSchema(def.schema.output));
  out.push("```");
  out.push("");

  // --- How it works (prose, extracted from the canonical header) ---
  out.push("## How it works");
  out.push("");
  out.push(
    "_Extracted from the `tool.ts` literate header (ADR-0043 Decision 5 — " +
      "the header is the canonical prose surface)._",
  );
  out.push("");
  out.push(renderHowItWorks(parsed));
  out.push("");

  // --- Invariants (mechanical, from def.invariants) ---
  out.push("## Invariants");
  out.push("");
  if (def.invariants.length === 0) {
    out.push("_(none declared)_");
  } else {
    for (const inv of def.invariants) {
      const mc =
        inv.machine_checkable === true
          ? " _(machine-checkable)_"
          : inv.machine_checkable === false
            ? " _(not machine-checkable)_"
            : "";
      out.push(`- **${inv.name}** — ${inv.statement}${mc}`);
    }
  }
  out.push("");

  // --- Run (mechanical, templated from the first worked example) ---
  out.push("## Run");
  out.push("");
  const ex = pickRunExample(def);
  if (ex === undefined) {
    out.push("_(no examples declared)_");
  } else {
    const inputJson = canonicalize(ex.input);
    const flagArgs =
      ex.flags === undefined
        ? ""
        : " " +
          Object.entries(ex.flags)
            .map(([k, v]) => `--${k}=${v}`)
            .join(" ");
    out.push("```sh");
    out.push(`echo '${inputJson}' \\`);
    out.push(`  | bun tools/${def.name}/tool.ts${flagArgs}`);
    if (ex.output !== undefined) {
      out.push(`# → ${canonicalize(ex.output)}`);
    }
    out.push("```");
    out.push("");
    if (ex.description !== undefined && String(ex.description).trim() !== "") {
      out.push(`Example: ${String(ex.description)}.`);
    }
    out.push("");
    out.push(
      `The tool ships ${def.examples.length} worked example` +
        `${def.examples.length === 1 ? "" : "s"} — run \`bun tools/${def.name}/tool.ts --examples\` ` +
        "to see them all.",
    );
  }
  out.push("");

  // --- Standard flags (constant) ---
  out.push("## Standard flags");
  out.push("");
  out.push("Every tool answers the standard-flag table (ADR-0011):");
  out.push("");
  out.push(
    "`--schema` `--examples` `--invariants` `--version` `--help` " +
      "`--provenance-of <hash>` `--test`",
  );
  if (def.arbprec === true) {
    out.push("");
    out.push(
      "This tool is `arbprec: true` (ADR-0020) and additionally answers " +
        "`--precision=<int>` (decimal digits, default 50) and " +
        "`--platform-fingerprint`.",
    );
  } else if (def.numerical === true) {
    out.push("");
    out.push(
      "This tool is `numerical: true` (ADR-0015) and additionally answers " +
        "`--platform-fingerprint`; float64-bearing outputs carry a " +
        "`platform` field in their provenance record.",
    );
  }
  out.push("");

  return out.join("\n");
}

/** A one-line determinism-tier annotation derived from the manifest flags. */
function determinismLine(def: ToolDefinition): string {
  if (def.nondeterministic === true) {
    return "`nondeterministic: true` (ADR-0005) — output may differ across runs given the same input.";
  }
  if (def.arbprec === true) {
    return (
      "`arbprec: true` (ADR-0020) — bit-identical cross-platform forever given " +
      "the `--precision` flag."
    );
  }
  if (def.numerical === true) {
    return (
      "`numerical: true` (ADR-0015) — bit-identical given the platform " +
      "fingerprint `{arch, os, runtime}`."
    );
  }
  return "symbolic — bit-identical cross-platform forever (the unconditional rule).";
}

// -----------------------------------------------------------------------------
// Main.
// -----------------------------------------------------------------------------

async function main(): Promise<void> {
  const toolsRoot = await findToolsRoot(ROOT);
  if (toolsRoot === null) {
    throw new Error(
      "gen-tool-readme: findToolsRoot returned null; run from inside the workbench checkout",
    );
  }

  const entries = await listToolEntries(toolsRoot);
  let wrote = 0;
  let current = 0;
  const drifted: string[] = [];

  for (const e of entries) {
    let def: ToolDefinition;
    try {
      def = await importToolDef(e.path);
    } catch (err) {
      throw new Error(
        `gen-tool-readme: failed to import ${e.path}: ${(err as Error).message}`,
      );
    }

    const source = await readFile(e.path, "utf8");
    const headerLines = extractHeaderBlock(source);
    const parsed = parseHeader(headerLines);

    // FAIL LOUD (Rule 1): the `Intent` section is the required anchor of
    // the extraction contract. A header with no `Intent` section has not
    // been written as the deliberate exposition Rule 10 + ADR-0043
    // Decision 5 require; emitting a thin README from it would silently
    // launder the gap. Name the tool and the missing section.
    const hasIntent = parsed.sections.some((s) => s.name === "Intent");
    if (!hasIntent) {
      throw new Error(
        `gen-tool-readme: tools/${e.name}/tool.ts literate header is missing the ` +
          `required \`Intent\` section. The header → README extraction contract ` +
          `(ADR-0043 Decision 5) requires every tool.ts header to carry an ` +
          `\`Intent\` underlined section as the anchor of its prose. Add an ` +
          `\`Intent\`\\n\`------\` section to the header, then rerun ` +
          `\`bun scripts/gen-tool-readme.ts\`.`,
      );
    }

    const next = renderReadme(def, parsed);
    const readmePath = join(toolsRoot, e.name, "README.md");

    let before: string | null = null;
    try {
      before = await readFile(readmePath, "utf8");
    } catch {
      // README does not exist yet — first generation.
    }

    if (before === next) {
      current++;
      continue;
    }
    drifted.push(e.name);
    if (!CHECK) {
      await writeFile(readmePath, next);
      wrote++;
    }
  }

  if (CHECK) {
    if (drifted.length > 0) {
      process.stderr.write(
        `gen-tool-readme --check: ${drifted.length} stale README(s): ${drifted.join(", ")}\n`,
      );
      process.exit(1);
    }
    process.stdout.write(
      `gen-tool-readme --check: all ${entries.length} READMEs current\n`,
    );
    return;
  }

  process.stdout.write(
    `gen-tool-readme: wrote ${wrote}, ${current} already current ` +
      `(${entries.length} tools)\n`,
  );
}

await main();
